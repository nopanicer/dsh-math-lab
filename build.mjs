/**
 * Build the client module.
 *
 * Sources live in `src/` and are plain script fragments: the Client loader gives
 * a plugin ONE module and ONE factory body, so the parts are concatenated in a
 * fixed order instead of being imported:
 *
 *   core.js      constants, storage, theme, plane view, drawing primitives,
 *                number parsing, model registries, side chart
 *   models/*.js  one file per model  (defineModel + optional defineLesson /
 *                defineQuiz / defineExams in the same file or in src/lessons,
 *                src/quizzes, src/exams)
 *   panel.js     the React panel + sidebar/main registration
 *
 * Every model file may decorate its own exports; nothing here understands the
 * math itself.
 */
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';

const here = new URL('./', import.meta.url);

/**
 * 参数：
 *   --only id1,id2   只拼这几个模型（各自并行开发时用，互不干扰）
 *   --out path       输出到指定文件（默认 client.js）
 */
const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
};
const only = (flag('--only') || '')
  .split(',')
  .map((id) => id.trim())
  .filter(Boolean);
const outPath = flag('--out') || 'client.js';

const read = async (relative) => (await readFile(new URL(relative, here), 'utf8')).replace(/\r\n/g, '\n');

async function listDir(dir) {
  try {
    const entries = await readdir(new URL(dir, here));
    return entries.filter((name) => name.endsWith('.js')).sort();
  } catch (_error) {
    return [];
  }
}

const core = await read('src/core.js');
const panel = await read('src/panel.js');

const sections = [
  ['src/models', '模型'],
  ['src/lessons', '讲解'],
  ['src/quizzes', '随机出题'],
  ['src/exams', '样例题'],
];

const parts = [];
for (const [dir, label] of sections) {
  let files = await listDir(dir);
  // 并行开发：--only 只保留对应 id 的模型文件；讲解/出题/例题目录只在完整构建时拼接
  if (only.length && dir === 'src/models') files = files.filter((file) => only.includes(file.replace(/\.js$/, '')));
  if (only.length && dir !== 'src/models') files = [];
  if (!files.length) continue;
  parts.push(`    // ${'='.repeat(74)}\n    // ${label}（${files.length} 个文件）\n    // ${'='.repeat(74)}\n`);
  for (const file of files) {
    const body = await read(`${dir}/${file}`);
    parts.push(`\n    // ---- ${dir}/${file} ${'-'.repeat(Math.max(4, 58 - dir.length - file.length))}\n`);
    parts.push(body.replace(/\r\n/g, '\n').trimEnd() + '\n');
  }
}

const output = `/**
 * dsh-math-lab — standalone build. Generated by build.mjs, do not edit.
 *
 * 高中数学动态实验室：纯客户端，解析解 + Canvas 2D，不调模型、不耗 token、不联网。
 */
window.__ModuleLoader__.load({
  id: 'dsh-math-lab',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const { useState, useEffect, useRef, useCallback } = React;

${core.trimEnd()}

${parts.join('')}
${panel.trimEnd()}
  },
});
`;

const target = new URL(outPath, here);
await mkdir(new URL('./', target), { recursive: true }).catch(() => {});
await writeFile(target, output);
const modelCount = parts.join('\n').split('defineModel(').length - 1;
console.log(`${outPath} written (${(output.length / 1024).toFixed(1)} KB, ${modelCount} models)`);
